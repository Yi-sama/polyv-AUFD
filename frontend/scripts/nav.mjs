// Navigation/transition checks in a real browser.
import { chromium } from 'playwright-core';
const BASE = process.env.BASE ?? 'http://127.0.0.1:5175';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const log = (...a) => console.log('·', ...a);
const url = () => new URL(page.url()).pathname;

await page.goto(BASE + '/');
await page.waitForSelector('.epg-row');
await page.hover('.epg-list li:nth-child(4) .epg-row');
log('monitor shows', await page.textContent('.monitor-name'));
await page.click('.epg-list li:nth-child(4) .epg-row');
await page.waitForSelector('.lower-third h1');
log('clicked row →', url(), await page.textContent('.lower-third h1'));
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(900);
log('→ key →', url(), await page.textContent('.bug b'));
await page.keyboard.press('ArrowLeft');
await page.waitForTimeout(900);
log('← key →', url());
await page.click('.wall-item:nth-child(2) .wall-link');
await page.waitForSelector('.viewer');
log('open work →', url(), await page.textContent('.viewer-info h2'));
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(400);
log('next work →', url());
await page.keyboard.press('Escape');
await page.waitForTimeout(700);
log('esc →', url(), 'viewer open:', await page.locator('.viewer').count());
await page.click('.wall-item:nth-child(1) .wall-link');
await page.waitForSelector('.viewer');
await page.click('.viewer-bar .icon-btn');
await page.waitForTimeout(700);
log('close button →', url());
await page.goBack();
await page.waitForTimeout(700);
log('browser back after close →', url(), 'viewer open:', await page.locator('.viewer').count());
await page.goForward(); await page.waitForTimeout(500);
await page.click('.next-channel');
await page.waitForTimeout(900);
log('next-channel card →', url());
await page.goto(BASE + '/tune');
await page.waitForSelector('.tune-slide');
await page.keyboard.press('ArrowDown');
await page.waitForTimeout(1200);
log('tune ↓ active', await page.textContent('.tune-rail .is-on'));
await page.keyboard.press('Enter');
await page.waitForTimeout(1200);
log('tune enter →', url());
await page.goto(BASE + '/?');
await page.fill('input[type=search]', '美食');
log('search 美食 rows', await page.locator('.epg-row').count());
await page.fill('input[type=search]', '');
await page.click('.tag:has-text("海报设计")');
log('tag 海报设计 rows', await page.locator('.epg-row').count());
await page.goto(BASE + '/no-such-one');
await page.waitForSelector('.notice');
log('404 →', await page.textContent('.notice-title'));
await browser.close();
console.log(errors.length ? 'PAGE ERRORS ' + errors.join(' | ') : 'no page errors');
